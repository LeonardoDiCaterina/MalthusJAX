#!/usr/bin/env python3
"""Generate tables and plots for TOML experiment result directories.

Expected input directory layout (generated by BenchmarkRunner):
- summary.json
- histories_combined.csv
- seed_XXXX/

Outputs are written under:
- <results_dir>/artifacts/
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import statistics
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, Iterable, List, Sequence


@dataclass
class MetricStats:
    metric: str
    count: int
    mean: float
    median: float
    stdev: float
    min_val: float
    max_val: float


def _is_number(value: Any) -> bool:
    try:
        f = float(value)
        return math.isfinite(f)
    except Exception:
        return False


def _fitness_sign_for_name(name: str) -> float:
    """Return sign normalization for pipeline/result names.

    Evosax native backends report best fitness with the opposite sign
    convention in this project, so we flip those for comparison artifacts.
    The wrapper pipeline `evosax_operators_in_mj` is still executed via the
    MalthusJAX engine and therefore should not be sign-flipped.
    """
    nl = name.lower()
    if "evosax_operators_in_mj" in nl:
        return 1.0
    if "evosax_native" in nl or "evosax_de" in nl or "evosax_simplega" in nl or "evosax_mr15" in nl:
        return -1.0
    return 1.0


def _normalize_metric(metric_key: str, value: float, fitness_sign: float) -> float:
    if "fitness" in metric_key:
        return value * fitness_sign
    return value


def _safe_float(value: Any) -> float | None:
    try:
        f = float(value)
    except Exception:
        return None
    return f if math.isfinite(f) else None


def load_summary(summary_path: Path) -> Dict[str, Any]:
    with summary_path.open("r") as f:
        return json.load(f)


def collect_metric_values(summary: Dict[str, Any], fitness_sign: float = 1.0) -> Dict[str, List[float]]:
    runs = summary.get("runs", [])
    metric_map: Dict[str, List[float]] = {}
    for run in runs:
        metrics = run.get("metrics", {})
        if not isinstance(metrics, dict):
            continue
        for key, value in metrics.items():
            v = _safe_float(value)
            if v is None:
                continue
            metric_map.setdefault(key, []).append(_normalize_metric(key, v, fitness_sign))
    return metric_map


def summarize_metrics(metric_map: Dict[str, List[float]]) -> List[MetricStats]:
    rows: List[MetricStats] = []
    for metric, values in sorted(metric_map.items()):
        if not values:
            continue
        rows.append(
            MetricStats(
                metric=metric,
                count=len(values),
                mean=statistics.mean(values),
                median=statistics.median(values),
                stdev=statistics.stdev(values) if len(values) > 1 else 0.0,
                min_val=min(values),
                max_val=max(values),
            )
        )
    return rows


def write_metrics_summary_csv(stats_rows: Sequence[MetricStats], out_path: Path) -> None:
    with out_path.open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["metric", "count", "mean", "median", "stdev", "min", "max"])
        for row in stats_rows:
            writer.writerow(
                [
                    row.metric,
                    row.count,
                    f"{row.mean:.12g}",
                    f"{row.median:.12g}",
                    f"{row.stdev:.12g}",
                    f"{row.min_val:.12g}",
                    f"{row.max_val:.12g}",
                ]
            )


def write_metrics_summary_md(stats_rows: Sequence[MetricStats], out_path: Path) -> None:
    lines = [
        "# Metrics Summary",
        "",
        "| Metric | Count | Mean | Median | StdDev | Min | Max |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for row in stats_rows:
        lines.append(
            f"| {row.metric} | {row.count} | {row.mean:.6g} | {row.median:.6g} | {row.stdev:.6g} | {row.min_val:.6g} | {row.max_val:.6g} |"
        )
    lines.append("")
    out_path.write_text("\n".join(lines))


def write_per_seed_metrics_csv(summary: Dict[str, Any], out_path: Path) -> None:
    runs = summary.get("runs", [])
    all_metric_keys: set[str] = set()
    for run in runs:
        metrics = run.get("metrics", {})
        if isinstance(metrics, dict):
            all_metric_keys.update(metrics.keys())

    metric_keys = sorted(all_metric_keys)
    base_cols = ["seed", "status", "duration_seconds", "error"]
    headers = base_cols + metric_keys

    fitness_sign = _fitness_sign_for_name(str(summary.get("name", "")))

    with out_path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=headers)
        writer.writeheader()
        for run in runs:
            row: Dict[str, Any] = {
                "seed": run.get("seed"),
                "status": run.get("status"),
                "duration_seconds": run.get("duration_seconds"),
                "error": run.get("error"),
            }
            metrics = run.get("metrics", {})
            if isinstance(metrics, dict):
                normalized_metrics: Dict[str, Any] = {}
                for key, value in metrics.items():
                    v = _safe_float(value)
                    if v is not None:
                        normalized_metrics[key] = _normalize_metric(key, v, fitness_sign)
                    else:
                        normalized_metrics[key] = value
                row.update(normalized_metrics)
            writer.writerow(row)


def _plot_convergence_from_csv(
    histories_csv: Path,
    metric_col: str,
    out_png: Path,
    fitness_sign: float = 1.0,
) -> bool:
    try:
        import pandas as pd
        import matplotlib.pyplot as plt
    except Exception:
        return False

    if not histories_csv.exists():
        return False

    try:
        df = pd.read_csv(histories_csv)
    except Exception:
        return False

    if "generation" not in df.columns or metric_col not in df.columns:
        return False

    grouped = (
        df.groupby("generation")[metric_col]
        .agg(["mean", "median", "std", "min", "max"])
        .reset_index()
        .sort_values("generation")
    )

    if "fitness" in metric_col:
        for col in ["mean", "median", "min", "max"]:
            grouped[col] = grouped[col] * fitness_sign

    fig, ax = plt.subplots(figsize=(9, 5))
    ax.plot(grouped["generation"], grouped["mean"], label="mean", linewidth=2)
    ax.plot(grouped["generation"], grouped["median"], label="median", linestyle="--", linewidth=1.5)
    ax.fill_between(
        grouped["generation"],
        grouped["min"],
        grouped["max"],
        alpha=0.15,
        label="min-max",
    )
    ax.set_title(f"Convergence: {metric_col}")
    ax.set_xlabel("generation")
    ax.set_ylabel(metric_col)
    ax.grid(True, alpha=0.3)
    ax.legend()
    fig.tight_layout()
    fig.savefig(out_png, dpi=180)
    plt.close(fig)
    return True


def _plot_per_seed_box(summary: Dict[str, Any], metric_key: str, out_png: Path) -> bool:
    try:
        import matplotlib.pyplot as plt
    except Exception:
        return False

    values: List[float] = []
    fitness_sign = _fitness_sign_for_name(str(summary.get("name", "")))
    for run in summary.get("runs", []):
        metrics = run.get("metrics", {})
        if not isinstance(metrics, dict):
            continue
        v = _safe_float(metrics.get(metric_key))
        if v is not None:
            values.append(_normalize_metric(metric_key, v, fitness_sign))

    if not values:
        return False

    fig, ax = plt.subplots(figsize=(4, 5))
    ax.boxplot(values, tick_labels=[metric_key], patch_artist=True)
    ax.set_title(f"Per-seed {metric_key}")
    ax.grid(True, axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(out_png, dpi=180)
    plt.close(fig)
    return True


def _find_pipeline_result_dirs(base_dir: Path) -> List[Path]:
    children: List[Path] = []
    for child in sorted(base_dir.iterdir()):
        if child.is_dir() and (child / "summary.json").exists():
            children.append(child)
    return children


def _collect_pipeline_rows(pipeline_dirs: Sequence[Path]) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    for pdir in pipeline_dirs:
        summary = load_summary(pdir / "summary.json")
        fitness_sign = _fitness_sign_for_name(pdir.name)
        metric_map = collect_metric_values(summary, fitness_sign=fitness_sign)
        best_vals = metric_map.get("best_fitness", [])
        duration_vals = [
            _safe_float(run.get("duration_seconds"))
            for run in summary.get("runs", [])
            if _safe_float(run.get("duration_seconds")) is not None
        ]
        rows.append(
            {
                "pipeline": pdir.name,
                "num_runs": len(summary.get("runs", [])),
                "best_fitness_mean": statistics.mean(best_vals) if best_vals else float("nan"),
                "best_fitness_stdev": statistics.stdev(best_vals) if len(best_vals) > 1 else 0.0,
                "duration_mean_s": statistics.mean(duration_vals) if duration_vals else float("nan"),
                "duration_stdev_s": statistics.stdev(duration_vals) if len(duration_vals) > 1 else 0.0,
            }
        )
    return rows


def _write_pipeline_comparison_tables(rows: Sequence[Dict[str, Any]], artifacts_dir: Path) -> Dict[str, str]:
    outputs: Dict[str, str] = {}

    csv_path = artifacts_dir / "comparison_table.csv"
    with csv_path.open("w", newline="") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "pipeline",
                "num_runs",
                "best_fitness_mean",
                "best_fitness_stdev",
                "duration_mean_s",
                "duration_stdev_s",
            ],
        )
        writer.writeheader()
        for row in rows:
            writer.writerow(row)
    outputs["comparison_table_csv"] = str(csv_path)

    md_path = artifacts_dir / "comparison_table.md"
    lines = [
        "# Pipeline Comparison",
        "",
        "| Pipeline | Runs | Best Fitness Mean ± StdDev | Duration Mean ± StdDev (s) |",
        "|---|---:|---:|---:|",
    ]
    for row in rows:
        lines.append(
            f"| {row['pipeline']} | {row['num_runs']} | "
            f"{row['best_fitness_mean']:.6g} ± {row['best_fitness_stdev']:.6g} | "
            f"{row['duration_mean_s']:.6g} ± {row['duration_stdev_s']:.6g} |"
        )
    lines.append("")
    md_path.write_text("\n".join(lines))
    outputs["comparison_table_md"] = str(md_path)

    return outputs


def _write_gap_summary(rows: Sequence[Dict[str, Any]], artifacts_dir: Path) -> Dict[str, str]:
    outputs: Dict[str, str] = {}
    comparisons: Dict[str, Dict[str, Any]] = {}
    target_suffixes = ["_evosax_simplega", "_mjx_evosax_exact"]

    for row in rows:
        pipeline = row["pipeline"]
        for suffix in target_suffixes:
            if pipeline.endswith(suffix):
                problem = pipeline[: -len(suffix)]
                comparisons.setdefault(problem, {})[suffix] = row
                break

    summary_rows: List[Dict[str, Any]] = []
    for problem in sorted(comparisons):
        data = comparisons[problem]
        if not all(suffix in data for suffix in target_suffixes):
            continue
        a = data[target_suffixes[0]]
        b = data[target_suffixes[1]]
        n = min(a["num_runs"], b["num_runs"])
        diff = a["best_fitness_mean"] - b["best_fitness_mean"]
        var = (a["best_fitness_stdev"] ** 2 / a["num_runs"]) + (b["best_fitness_stdev"] ** 2 / b["num_runs"])
        se = math.sqrt(var) if var >= 0 else float("nan")
        pooled = math.sqrt(
            ((a["num_runs"] - 1) * a["best_fitness_stdev"] ** 2
             + (b["num_runs"] - 1) * b["best_fitness_stdev"] ** 2)
            / (a["num_runs"] + b["num_runs"] - 2)
        ) if a["num_runs"] > 1 and b["num_runs"] > 1 else float("nan")
        t_stat = diff / pooled if pooled > 0 else float("nan")
        rel_diff = abs(diff) / (abs(b["best_fitness_mean"]) if abs(b["best_fitness_mean"]) > 1e-9 else 1.0)
        summary_rows.append(
            {
                "problem": problem,
                "runs": n,
                "evosax_simplega_mean": a["best_fitness_mean"],
                "evosax_simplega_stdev": a["best_fitness_stdev"],
                "mjx_evosax_exact_mean": b["best_fitness_mean"],
                "mjx_evosax_exact_stdev": b["best_fitness_stdev"],
                "mean_diff": diff,
                "abs_diff": abs(diff),
                "rel_diff": rel_diff,
                "se_diff": se,
                "pooled_stdev": pooled,
                "t_stat": t_stat,
            }
        )

    csv_path = artifacts_dir / "gap_summary.csv"
    with csv_path.open("w", newline="") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "problem",
                "runs",
                "evosax_simplega_mean",
                "evosax_simplega_stdev",
                "mjx_evosax_exact_mean",
                "mjx_evosax_exact_stdev",
                "mean_diff",
                "abs_diff",
                "rel_diff",
                "se_diff",
                "pooled_stdev",
                "t_stat",
            ],
        )
        writer.writeheader()
        for row in summary_rows:
            writer.writerow(
                {k: (f"{v:.12g}" if isinstance(v, float) else v) for k, v in row.items()}
            )
    outputs["gap_summary_csv"] = str(csv_path)

    md_path = artifacts_dir / "gap_summary.md"
    lines = [
        "# Gap Summary: Evosax SimpleGA vs MalthusJAX Evosax Exact",
        "",
        "| Problem | Runs | Evosax SimpleGA Mean ± StdDev | MJX Evosax Exact Mean ± StdDev | Mean Diff | Abs Diff | Rel Diff | SE Diff | t-stat |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for row in summary_rows:
        lines.append(
            f"| {row['problem']} | {row['runs']} | "
            f"{float(row['evosax_simplega_mean']):.6g} ± {float(row['evosax_simplega_stdev']):.6g} | "
            f"{float(row['mjx_evosax_exact_mean']):.6g} ± {float(row['mjx_evosax_exact_stdev']):.6g} | "
            f"{float(row['mean_diff']):.6g} | {float(row['abs_diff']):.6g} | {float(row['rel_diff']):.6g} | {float(row['se_diff']):.6g} | {float(row['t_stat']):.6g} |"
        )
    lines.append("")
    md_path.write_text("\n".join(lines))
    outputs["gap_summary_md"] = str(md_path)

    return outputs


def _plot_pipeline_comparison_boxplots(pipeline_dirs: Sequence[Path], artifacts_dir: Path) -> Dict[str, str]:
    try:
        import matplotlib.pyplot as plt
    except Exception:
        return {}

    outputs: Dict[str, str] = {}

    labels: List[str] = []
    best_data: List[List[float]] = []
    dur_data: List[List[float]] = []

    for pdir in pipeline_dirs:
        summary = load_summary(pdir / "summary.json")
        fitness_sign = _fitness_sign_for_name(pdir.name)
        metric_map = collect_metric_values(summary, fitness_sign=fitness_sign)
        best_vals = metric_map.get("best_fitness", [])
        duration_vals = [
            _safe_float(run.get("duration_seconds"))
            for run in summary.get("runs", [])
            if _safe_float(run.get("duration_seconds")) is not None
        ]
        if best_vals:
            labels.append(pdir.name)
            best_data.append(best_vals)
            dur_data.append(duration_vals if duration_vals else [0.0])

    if not best_data:
        return outputs

    fig, ax = plt.subplots(figsize=(max(6, len(labels) * 1.4), 5))
    try:
        ax.boxplot(best_data, tick_labels=labels, patch_artist=True)
    except TypeError:
        ax.boxplot(best_data, labels=labels, patch_artist=True)
    ax.set_title("Final Best Fitness by Pipeline")
    ax.set_ylabel("best_fitness")
    ax.set_xlabel("pipeline")
    ax.tick_params(axis="x", labelrotation=25)
    ax.grid(True, axis="y", alpha=0.3)
    fig.tight_layout()
    best_path = artifacts_dir / "comparison_final_best_fitness_boxplot.png"
    fig.savefig(best_path, dpi=180)
    plt.close(fig)
    outputs["comparison_final_best_fitness_boxplot_png"] = str(best_path)

    fig, ax = plt.subplots(figsize=(max(6, len(labels) * 1.4), 5))
    try:
        ax.boxplot(dur_data, tick_labels=labels, patch_artist=True)
    except TypeError:
        ax.boxplot(dur_data, labels=labels, patch_artist=True)
    ax.set_title("Duration by Pipeline")
    ax.set_ylabel("duration_seconds")
    ax.set_xlabel("pipeline")
    ax.tick_params(axis="x", labelrotation=25)
    ax.grid(True, axis="y", alpha=0.3)
    fig.tight_layout()
    dur_path = artifacts_dir / "comparison_timing_boxplot.png"
    fig.savefig(dur_path, dpi=180)
    plt.close(fig)
    outputs["comparison_timing_boxplot_png"] = str(dur_path)

    return outputs


def _plot_pipeline_convergence(pipeline_dirs: Sequence[Path], artifacts_dir: Path) -> Dict[str, str]:
    try:
        import pandas as pd
        import matplotlib.pyplot as plt
    except Exception:
        return {}

    outputs: Dict[str, str] = {}
    fig, ax = plt.subplots(figsize=(9, 5))
    plotted = 0

    for pdir in pipeline_dirs:
        csv_path = pdir / "histories_combined.csv"
        if not csv_path.exists():
            continue
        try:
            df = pd.read_csv(csv_path)
        except Exception:
            continue
        if "generation" not in df.columns or "best_fitness" not in df.columns:
            continue
        grouped = (
            df.groupby("generation")["best_fitness"]
            .mean()
            .reset_index()
            .sort_values("generation")
        )
        grouped["best_fitness"] = grouped["best_fitness"] * _fitness_sign_for_name(pdir.name)
        ax.plot(grouped["generation"], grouped["best_fitness"], label=pdir.name, linewidth=2)
        plotted += 1

    if plotted == 0:
        plt.close(fig)
        return outputs

    ax.set_title("Convergence Comparison (mean best_fitness)")
    ax.set_xlabel("generation")
    ax.set_ylabel("best_fitness")
    ax.grid(True, alpha=0.3)
    ax.legend(loc="best")
    fig.tight_layout()
    out_path = artifacts_dir / "comparison_convergence_best_fitness.png"
    fig.savefig(out_path, dpi=180)
    plt.close(fig)
    outputs["comparison_convergence_best_fitness_png"] = str(out_path)
    return outputs


def generate_pipeline_comparison_artifacts(base_dir: Path) -> Dict[str, str]:
    pipeline_dirs = _find_pipeline_result_dirs(base_dir)
    if len(pipeline_dirs) < 2:
        return {}

    artifacts_dir = base_dir / "artifacts"
    artifacts_dir.mkdir(parents=True, exist_ok=True)

    outputs: Dict[str, str] = {}
    rows = _collect_pipeline_rows(pipeline_dirs)
    outputs.update(_write_pipeline_comparison_tables(rows, artifacts_dir))
    outputs.update(_write_gap_summary(rows, artifacts_dir))
    outputs.update(_plot_pipeline_comparison_boxplots(pipeline_dirs, artifacts_dir))
    outputs.update(_plot_pipeline_convergence(pipeline_dirs, artifacts_dir))
    return outputs


def _resolve_results_dirs(results_dir: str | None, results_glob: str | None) -> List[Path]:
    if results_dir:
        return [Path(results_dir)]
    if not results_glob:
        return []
    return sorted(Path().glob(results_glob))


def generate_for_results_dir(results_dir: Path) -> Dict[str, Any]:
    summary_json = results_dir / "summary.json"
    histories_csv = results_dir / "histories_combined.csv"

    if not summary_json.exists():
        raise FileNotFoundError(f"Missing summary.json in {results_dir}")

    artifacts_dir = results_dir / "artifacts"
    artifacts_dir.mkdir(parents=True, exist_ok=True)

    summary = load_summary(summary_json)
    fitness_sign = _fitness_sign_for_name(str(summary.get("name", "")))
    metric_map = collect_metric_values(summary, fitness_sign=fitness_sign)
    stats_rows = summarize_metrics(metric_map)

    outputs: Dict[str, str] = {}

    metrics_csv = artifacts_dir / "metrics_summary.csv"
    write_metrics_summary_csv(stats_rows, metrics_csv)
    outputs["metrics_summary_csv"] = str(metrics_csv)

    metrics_md = artifacts_dir / "metrics_summary.md"
    write_metrics_summary_md(stats_rows, metrics_md)
    outputs["metrics_summary_md"] = str(metrics_md)

    per_seed_csv = artifacts_dir / "per_seed_metrics.csv"
    write_per_seed_metrics_csv(summary, per_seed_csv)
    outputs["per_seed_metrics_csv"] = str(per_seed_csv)

    if _plot_convergence_from_csv(
        histories_csv,
        "best_fitness",
        artifacts_dir / "convergence_best_fitness.png",
        fitness_sign=fitness_sign,
    ):
        outputs["convergence_best_fitness_png"] = str(artifacts_dir / "convergence_best_fitness.png")

    if _plot_convergence_from_csv(
        histories_csv,
        "mean_fitness",
        artifacts_dir / "convergence_mean_fitness.png",
        fitness_sign=fitness_sign,
    ):
        outputs["convergence_mean_fitness_png"] = str(artifacts_dir / "convergence_mean_fitness.png")

    if _plot_per_seed_box(summary, "best_fitness", artifacts_dir / "final_best_fitness_boxplot.png"):
        outputs["final_best_fitness_boxplot_png"] = str(artifacts_dir / "final_best_fitness_boxplot.png")

    index_path = artifacts_dir / "artifact_index.json"
    index_payload = {
        "results_dir": str(results_dir),
        "generated": outputs,
        "num_runs": len(summary.get("runs", [])),
        "experiment_name": summary.get("name"),
    }
    index_path.write_text(json.dumps(index_payload, indent=2))
    outputs["artifact_index_json"] = str(index_path)

    return {
        "results_dir": str(results_dir),
        "outputs": outputs,
        "ok": True,
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate plots and tables for experiment result directories"
    )
    parser.add_argument("--results-dir", type=str, default=None, help="Single result directory")
    parser.add_argument(
        "--results-glob",
        type=str,
        default=None,
        help="Glob for multiple result directories (e.g. 'results/bbob_*_pop1024')",
    )
    args = parser.parse_args()

    result_dirs = _resolve_results_dirs(args.results_dir, args.results_glob)
    if not result_dirs:
        print("Error: no result directories matched")
        return 1

    failures: List[str] = []
    reports: List[Dict[str, Any]] = []

    for result_dir in result_dirs:
        try:
            report = None
            outputs: Dict[str, str] = {}
            pipeline_dirs = _find_pipeline_result_dirs(result_dir)

            summary_json = result_dir / "summary.json"
            # If multiple pipeline subdirectories exist, prefer comparison mode
            # and skip root-level single-run artifacts (which may be stale).
            if summary_json.exists() and len(pipeline_dirs) < 2:
                report = generate_for_results_dir(result_dir)
                outputs.update(report["outputs"])

            comparison_outputs = generate_pipeline_comparison_artifacts(result_dir)
            outputs.update(comparison_outputs)

            if report is None:
                report = {
                    "results_dir": str(result_dir),
                    "outputs": outputs,
                    "ok": bool(outputs),
                }
            else:
                report["outputs"] = outputs

            if not outputs:
                raise FileNotFoundError(
                    f"No summary.json found directly in {result_dir} and no pipeline subdirectories with summary.json"
                )

            reports.append(report)
            print(f"[ok] {result_dir}")
            for key, path in report["outputs"].items():
                print(f"  - {key}: {path}")
        except Exception as exc:
            failures.append(f"{result_dir}: {exc}")
            print(f"[error] {result_dir}: {exc}")

    if failures:
        print("\nSome directories failed:")
        for fail in failures:
            print(f"  - {fail}")
        return 2

    print(f"\nGenerated artifacts for {len(reports)} directory(ies).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
